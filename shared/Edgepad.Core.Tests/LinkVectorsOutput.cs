using Edgepad.Net;
using Xunit;

namespace Edgepad.Tests;

/// <summary>
/// The EDGL1 vectors the Kotlin and Swift ports check themselves against, worked out by the same code the laptop
/// runs, from fixed inputs: RFC 5903's two P-256 key pairs (phone = i, laptop = r), ids and nonces of counting bytes.
/// Written to protocol/link-vectors.txt only when <c>EDGEPAD_LINK_VECTORS_OUT</c> names a file (CI sets it and
/// uploads the file); otherwise the test only checks the lines come out the same twice.
/// </summary>
public sealed class LinkVectorsOutput
{
    private static readonly byte[] PhoneId = Counting(0x00, 16);
    private static readonly byte[] LaptopId = Counting(0x10, 16);
    private static readonly byte[] PairPhoneNonce = Counting(0x20, 16);
    private static readonly byte[] PairLaptopNonce = Counting(0x30, 16);
    private static readonly byte[] ResumePhoneNonce = Counting(0x40, 16);
    private static readonly byte[] ResumeLaptopNonce = Counting(0x50, 16);
    private static readonly byte[] Plain = "EDGL1 record"u8.ToArray();
    private static readonly byte[] PhoneName = LinkWire.NameField("Phone");
    private static readonly byte[] LaptopName = LinkWire.NameField("Laptop");

    [Fact]
    public void WritesTheLinkVectorsWhenAsked()
    {
        var lines = Lines();
        Assert.Equal(lines, Lines());

        var path = Environment.GetEnvironmentVariable("EDGEPAD_LINK_VECTORS_OUT");
        if (!string.IsNullOrEmpty(path))
        {
            File.WriteAllLines(path, lines);
        }
    }

    internal static List<string> Lines()
    {
        using var phone = LinkCryptoTests.Fixed(LinkCryptoTests.I, LinkCryptoTests.Gix, LinkCryptoTests.Giy);
        using var laptop = LinkCryptoTests.Fixed(LinkCryptoTests.R, LinkCryptoTests.Grx, LinkCryptoTests.Gry);
        List<string> lines =
        [
            "# EDGL1 vectors for the Edgepad network link (docs/PROTOCOL.md). Generated by the core test",
            "# LinkVectorsOutput with EDGEPAD_LINK_VECTORS_OUT set; do not edit by hand. The C#, Kotlin and Swift",
            "# suites all read this file and must derive every value on each line from the INPUT line before it.",
            "#",
            "# Format:  NAME key=value ...   Values are hex, except sas (six decimal digits) and counter (decimal).",
            "# nameP and nameL are the names as sent: a length byte, then UTF-8. Only a pairing hashes them.",
            "# Keys are RFC 5903 section 8.1's: the phone uses i, the laptop r. Records are sealed by the phone.",
            "",
        ];

        // Pairing.
        var pairTh = LinkCrypto.PairTranscript(PhoneId, LaptopId, PhoneName, LaptopName, phone.PublicKey, PairPhoneNonce, laptop.PublicKey, PairLaptopNonce);
        var pairPrk = LinkCrypto.PairPrk(pairTh, LinkCrypto.Agree(laptop, phone.PublicKey));
        var pairingKey = LinkCrypto.PairingKey(pairPrk);
        lines.Add(Line(
            "PAIR_INPUT",
            ("dP", Hex(LinkCryptoTests.I)),
            ("dL", Hex(LinkCryptoTests.R)),
            ("pkP", phone.PublicKey),
            ("pkL", laptop.PublicKey),
            ("phoneId", PhoneId),
            ("laptopId", LaptopId),
            ("nameP", PhoneName),
            ("nameL", LaptopName),
            ("nP", PairPhoneNonce),
            ("nL", PairLaptopNonce)));
        lines.Add(Line(
            "PAIR",
            ("commit", LinkCrypto.Commit(phone.PublicKey, PairPhoneNonce)),
            ("z", LinkCrypto.Agree(phone, laptop.PublicKey)),
            ("th", pairTh)) + " sas=" + LinkCrypto.Sas(pairTh));
        lines.Add(Line(
            "PAIR_KEYS",
            ("prk", pairPrk),
            ("tagL", LinkCrypto.LaptopTag(pairPrk, pairTh, pairing: true)),
            ("tagP", LinkCrypto.PhoneTag(pairPrk, pairTh, pairing: true)),
            ("pk", pairingKey)));
        lines.AddRange(Session("PAIR", pairPrk));

        // Resuming with the key that pairing left.
        var resumeTh = LinkCrypto.ResumeTranscript(PhoneId, LaptopId, phone.PublicKey, ResumePhoneNonce, laptop.PublicKey, ResumeLaptopNonce);
        var resumePrk = LinkCrypto.ResumePrk(resumeTh, LinkCrypto.Agree(laptop, phone.PublicKey), pairingKey);
        lines.Add("");
        lines.Add(Line("RESUME_INPUT", ("pk", pairingKey), ("nP", ResumePhoneNonce), ("nL", ResumeLaptopNonce)));
        lines.Add(Line(
            "RESUME",
            ("th", resumeTh),
            ("prk", resumePrk),
            ("tagL", LinkCrypto.LaptopTag(resumePrk, resumeTh, pairing: false)),
            ("tagP", LinkCrypto.PhoneTag(resumePrk, resumeTh, pairing: false))));
        lines.AddRange(Session("RESUME", resumePrk));
        return lines;
    }

    // The direction keys, then the same plaintext sealed twice by the phone, as counters 0 and 1.
    private static IEnumerable<string> Session(string name, byte[] prk)
    {
        var (p2l, l2p, iv) = LinkCrypto.SessionKeys(prk);
        yield return Line(name + "_SESSION", ("kP2L", p2l), ("kL2P", l2p), ("iv", iv));

        using var wire = new MemoryStream();
        using var phone = new SecureStream(wire, prk, isPhone: true);
        for (var counter = 0; counter < 2; counter++)
        {
            var before = (int)wire.Length;
            phone.Write(Plain);
            yield return Line(name + "_RECORD", ("plain", Plain), ("record", wire.ToArray()[before..])).Replace(
                name + "_RECORD ",
                $"{name}_RECORD counter={counter} ",
                StringComparison.Ordinal);
        }
    }

    private static string Line(string name, params (string Key, byte[] Value)[] fields) =>
        name + string.Concat(fields.Select(f => $" {f.Key}={Convert.ToHexStringLower(f.Value)}"));

    private static byte[] Hex(string hex) => Convert.FromHexString(hex);

    private static byte[] Counting(int from, int count) => [.. Enumerable.Range(from, count).Select(i => (byte)i)];
}
