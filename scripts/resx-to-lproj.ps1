# Turns the Mac app's resx files into the .lproj folders SwiftPM and bundle.sh read.
#
#   pwsh scripts/resx-to-lproj.ps1           writes the folders, after checking
#   pwsh scripts/resx-to-lproj.ps1 -Check    checks only; writes nothing; exits non-zero on a finding
#
# Reads macos/Localization/MacStrings*.resx and shared/Edgepad.Core/CoreStrings*.resx and writes, per language:
#   macos/Sources/Edgepad/Resources/<lang>.lproj/Localizable.strings   MacStrings keys without the Info_ prefix
#   macos/Sources/Edgepad/Resources/<lang>.lproj/InfoPlist.strings     MacStrings keys Info_<plist key>
#   macos/Sources/EdgepadCore/Resources/<lang>.lproj/Localizable.strings   CoreStrings keys
# {0} becomes %1$@, {1} becomes %2$@. The check fails on a key missing from a language, on placeholders that differ
# from English, and on a Swift tr("Key", "English") whose English differs from the resx. Runs on Windows, Linux and
# macOS (pwsh); CI calls it on the macOS runner before `swift build`.
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$langs = 'en', 'ar', 'de', 'es', 'fr', 'hi', 'it', 'ja', 'ko', 'nl', 'pl', 'pt-BR', 'ru', 'tr', 'zh-Hans'
$problems = [System.Collections.Generic.List[string]]::new()

function Read-Resx([string]$stem, [string]$lang) {
    $suffix = if ($lang -eq 'en') { '' } else { ".$lang" }
    $path = "$stem$suffix.resx"
    $map = [ordered]@{}
    if (-not (Test-Path $path)) { $problems.Add("missing file $path"); return $map }
    foreach ($d in ([xml](Get-Content -Raw -Encoding utf8 $path)).root.data) { $map[$d.name] = [string]$d.value }
    return $map
}

# The Swift default string is already in %1$@ form; resx values use {0}.
function ConvertTo-Format([string]$v) {
    [regex]::Replace($v.Replace('%', '%%'), '\{(\d+)\}', { param($m) '%' + ([int]$m.Groups[1].Value + 1) + '$@' })
}

function Get-Placeholders([string]$v) {
    ([regex]::Matches($v, '\{(\d+)\}') | ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique) -join ','
}

function ConvertTo-Literal([string]$v) {
    '"' + $v.Replace('\', '\\').Replace('"', '\"').Replace("`r", '').Replace("`n", '\n') + '"'
}

function Write-Strings([string]$dir, [string]$file, $pairs) {
    $text = "/* Generated by scripts/resx-to-lproj.ps1 from the resx files. Do not edit. */`n"
    foreach ($k in $pairs.Keys) { $text += "$(ConvertTo-Literal $k) = $(ConvertTo-Literal (ConvertTo-Format $pairs[$k]));`n" }
    if ($Check) { return }
    New-Item -ItemType Directory -Force $dir | Out-Null
    [IO.File]::WriteAllText((Join-Path $dir $file), $text, [Text.UTF8Encoding]::new($false))
}

$sets = @(
    @{ Stem = Join-Path $root 'macos/Localization/MacStrings'; Out = Join-Path $root 'macos/Sources/Edgepad/Resources'; Info = $true },
    @{ Stem = Join-Path $root 'shared/Edgepad.Core/CoreStrings'; Out = Join-Path $root 'macos/Sources/EdgepadCore/Resources'; Info = $false }
)
$english = @{}
foreach ($set in $sets) {
    $en = Read-Resx $set.Stem 'en'
    foreach ($k in $en.Keys) { $english[$k] = $en[$k] }
    foreach ($lang in $langs) {
        $tr = Read-Resx $set.Stem $lang
        foreach ($k in $en.Keys) {
            if (-not $tr.Contains($k)) { $problems.Add("$($set.Stem).$lang.resx lacks $k"); continue }
            if ((Get-Placeholders $tr[$k]) -ne (Get-Placeholders $en[$k])) { $problems.Add("$($set.Stem).$lang.resx $k has other placeholders than English") }
        }
        $words = [ordered]@{}; $info = [ordered]@{}
        foreach ($k in $en.Keys) {
            if (-not $tr.Contains($k)) { continue }
            if ($set.Info -and $k.StartsWith('Info_')) { $info[$k.Substring(5)] = $tr[$k] } else { $words[$k] = $tr[$k] }
        }
        $dir = Join-Path $set.Out "$lang.lproj"
        if ($words.Count) { Write-Strings $dir 'Localizable.strings' $words }
        if ($info.Count) { Write-Strings $dir 'InfoPlist.strings' $info }
    }
}

# Every tr("Key", "English") in Swift carries the English the resx holds, so a missing lookup shows the same words.
$call = [regex]'\btr\(\s*"(?<k>(?:[^"\\]|\\.)*)"\s*,\s*"(?<e>(?:[^"\\]|\\.)*)"'
foreach ($f in Get-ChildItem (Join-Path $root 'macos/Sources') -Recurse -Filter *.swift) {
    foreach ($m in $call.Matches((Get-Content -Raw -Encoding utf8 $f.FullName))) {
        $k = $m.Groups['k'].Value
        $e = [regex]::Replace($m.Groups['e'].Value, '\\(.)', { param($x) if ($x.Groups[1].Value -eq 'n') { "`n" } else { $x.Groups[1].Value } })
        if (-not $english.ContainsKey($k)) { $problems.Add("$($f.Name): tr key $k is in no resx"); continue }
        if ((ConvertTo-Format $english[$k]) -ne $e) { $problems.Add("$($f.Name): tr(`"$k`") English differs from the resx") }
    }
}

if ($problems.Count) { $problems | ForEach-Object { Write-Error $_ -ErrorAction Continue }; exit 1 }
Write-Host "resx-to-lproj: $($langs.Count) languages ok$(if ($Check) { ' (check only)' })"
