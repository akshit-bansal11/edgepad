/// Which of the types a pasteboard offers is shared, and which mean it must not be. Pure, so the choice is tested
/// without a pasteboard. The raw strings are the UTIs of `NSPasteboard.PasteboardType.string`, `.png` and `.tiff`.
public enum PasteboardTypes {
    public enum Pick: Equatable {
        /// A password manager or the app that wrote it asked for this not to be kept or shared.
        case sensitive
        case text
        case png
        case tiff
        case nothing
    }

    /// The conventions at nspasteboard.org: concealed (a password), transient (gone soon) and auto-generated (not the
    /// user's own copy).
    public static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    public static let text = "public.utf8-plain-text"
    public static let png = "public.png"
    public static let tiff = "public.tiff"

    /// A sensitive marker beats everything. Then text, since an app that offers text and an image together (a
    /// spreadsheet) means the text, then a PNG, then a TIFF.
    public static func pick(_ offered: [String]) -> Pick {
        let types = Set(offered)
        if !types.isDisjoint(with: sensitiveTypes) {
            return .sensitive
        }
        if types.contains(text) {
            return .text
        }
        if types.contains(png) {
            return .png
        }
        if types.contains(tiff) {
            return .tiff
        }
        return .nothing
    }
}
